#!/bin/bash
# bash scripts/install_cpp_env.sh && source ~/.bashrc
# 每个组件一律先 purge 再装，重跑会重装全部 (含重编 GDB)。系统 python3 不动，仅 purge 目标版本
# 以子进程运行而非 source：set -e 失败只退出脚本，不会关掉交互终端；PATH 等经 ENV_FILE 在新终端生效

if [[ "${BASH_SOURCE[0]}" != "${0}" ]]; then
    echo "请直接执行，不要 source: bash $BASH_SOURCE" >&2
    return 1
fi

if [ "$(uname -m)" != "x86_64" ] || [ "$(uname -s)" != "Linux" ] || ! command -v apt-get &> /dev/null; then
    echo "仅支持 Linux x86_64 + apt" >&2
    exit 1
fi

set -eo pipefail
trap 'echo "[FATAL] line $LINENO: $BASH_COMMAND" >&2' ERR

NVM_VERSION="0.40.8"
NODE_VERSION="24.22.1"
PYTHON_TARGET="3.15"
GO_VERSION="1.27.3"
CMAKE_VERSION="4.4.4"
CCACHE_VERSION="4.14.2"
LLVM_VERSION="23"
GCC_VERSION="16"
NINJA_VERSION="1.13.2"
MOLD_VERSION="2.42.1"
GDB_VERSION="18.1"
VCPKG_TAG="2026.10.16"

# root (如 docker) 下 sudo 退化为 env：既执行普通命令，也兼容 `sudo VAR=val cmd`；非 root 且无 sudo 则报错
if [ "$(id -u)" -eq 0 ]; then
    sudo() { env "$@"; }
elif ! command -v sudo &> /dev/null; then
    echo "需要 root 或已安装 sudo" >&2
    exit 1
fi

apt_run() { sudo DEBIAN_FRONTEND=noninteractive apt-get -y -qq "$@"; }

installed() {
    dpkg-query -W -f='${db:Status-Abbrev} ${Package}\n' 2>/dev/null \
        | awk -v re="$1" '$1=="ii" && $2 ~ re {print $2}'
}

purge() {
    local pkgs
    [ -n "$1" ] || return 1
    pkgs="$(installed "$1" | tr '\n' ' ')"
    [ -z "$pkgs" ] || apt_run purge $pkgs
}

bashrc_add() { grep -qxF "$1" ~/.bashrc || echo "$1" >> ~/.bashrc; }

# 环境变量集中写入 ENV_FILE，~/.bashrc 只 source 它。~/.bashrc 在非交互 shell 里提前 return，
# 脚本 / cron / docker exec 须显式 source ENV_FILE (或 BASH_ENV=ENV_FILE)
ENV_FILE="$HOME/.cpp_env.sh"
env_add() { grep -qxF "$1" "$ENV_FILE" || echo "$1" >> "$ENV_FILE"; }
echo '# generated by scripts/install_cpp_env.sh' > "$ENV_FILE"
bashrc_add "[ -f $ENV_FILE ] && . $ENV_FILE"

add_ppa() {
    local ppa="$1" fpr="$2" codename key
    codename="$(. /etc/os-release && echo "$VERSION_CODENAME")"
    key="/etc/apt/keyrings/${ppa//\//-}.gpg"
    grep -rqs "ppa.launchpadcontent.net/${ppa}/ubuntu" /etc/apt/sources.list.d/ && return 0
    sudo install -d -m 0755 /etc/apt/keyrings
    curl -fsSL "https://keyserver.ubuntu.com/pks/lookup?op=get&search=0x${fpr}" | gpg --dearmor | sudo tee "$key" > /dev/null
    printf 'Types: deb\nURIs: https://ppa.launchpadcontent.net/%s/ubuntu/\nSuites: %s\nComponents: main\nSigned-By: %s\n' \
        "$ppa" "$codename" "$key" | sudo tee "/etc/apt/sources.list.d/${ppa//\//-}.sources" > /dev/null
    apt_run update
}

add_llvm_repo() {
    local codename
    codename="$(. /etc/os-release && echo "$VERSION_CODENAME")"
    grep -rqs "llvm-toolchain-${codename}-${LLVM_VERSION}" /etc/apt/sources.list.d/ && return 0
    sudo install -d -m 0755 /etc/apt/keyrings
    curl -fsSL https://apt.llvm.org/llvm-snapshot.gpg.key | sudo tee /etc/apt/keyrings/apt.llvm.org.asc > /dev/null
    printf 'Types: deb\nURIs: https://apt.llvm.org/%s/\nSuites: llvm-toolchain-%s-%s\nComponents: main\nSigned-By: /etc/apt/keyrings/apt.llvm.org.asc\n' \
        "$codename" "$codename" "$LLVM_VERSION" | sudo tee "/etc/apt/sources.list.d/llvm-${LLVM_VERSION}.sources" > /dev/null
    apt_run update
}

# Step 0: 阿里云镜像 (仅 24.04 的 deb822 格式)
if [ -f /etc/apt/sources.list.d/ubuntu.sources ]; then
    sudo sed -i 's/archive.ubuntu.com/mirrors.aliyun.com/g; s/security.ubuntu.com/mirrors.aliyun.com/g' \
        /etc/apt/sources.list.d/ubuntu.sources
fi

# Step 1: 系统工具
COMMON_DEPS=(
    "ca-certificates" "gnupg" "lsb-release"
    "make" "pkg-config" "zip" "unzip" "tar" "xz-utils"
    "curl" "wget" "net-tools" "iproute2" "dnsutils" "tcpdump" "netcat-openbsd"
    "htop" "strace" "valgrind" "lsof" "sysstat" "pstack"
    "git" "jq" "vim" "tree" "rsync"
    "autoconf" "automake" "libtool" "bison" "flex"
)
apt_run update
apt_run install "${COMMON_DEPS[@]}"

# Step 2: Node.js (nvm)
purge '^(nodejs|npm|libnode[0-9]*)$'
rm -rf "$HOME/.nvm"
export NVM_DIR="$HOME/.nvm"
env_add 'export NVM_DIR="$HOME/.nvm"'
env_add '[ -s "$NVM_DIR/nvm.sh" ] && . "$NVM_DIR/nvm.sh"'
wget -qO- "https://raw.githubusercontent.com/nvm-sh/nvm/v${NVM_VERSION}/install.sh" | bash > /dev/null
# nvm.sh 内部有函数在正常流程里返回非零，source 期间不能带 -e
set +e
# shellcheck disable=SC1091
source "$NVM_DIR/nvm.sh"
set -e
nvm install "$NODE_VERSION" > /dev/null
nvm alias default "$NODE_VERSION" > /dev/null

# Step 3: Claude Code + opencode
npm install -g @anthropic-ai/claude-code > /dev/null
npm install -g @opencode/cli > /dev/null
# nvm 路径带版本号，软链到系统路径让不加载 ENV_FILE 的场景也能直接调用。交互 shell 里 nvm 的 PATH 在前，不影响 nvm use 切版本
for _t in node npm npx claude opencode; do
    sudo ln -sf "$(command -v "$_t")" "/usr/local/bin/$_t"
done
unset _t

# Step 4: Python
# 系统 python3 不动 (apt、cloud-init 等依赖它)。只 purge 目标版本，再经 ~/.local/bin 让 python/python3 解析到它。
# 不放 /usr/local/bin：它在 sudo secure_path 里，会让 sudo 与 `#!/usr/bin/env python3` 的系统脚本改用目标版本
purge "^(python${PYTHON_TARGET//./[.]}(-.*)?|libpython${PYTHON_TARGET//./[.]}(-.*)?)$"
add_ppa deadsnakes/ppa F23C5A6CF475977595C89F51BA6932366A755776
apt_run install "python${PYTHON_TARGET}" "python${PYTHON_TARGET}-dev" "python${PYTHON_TARGET}-venv"
mkdir -p "$HOME/.local/bin"
ln -sf "/usr/bin/python${PYTHON_TARGET}" "$HOME/.local/bin/python3"
ln -sf "/usr/bin/python${PYTHON_TARGET}" "$HOME/.local/bin/python"
env_add 'export PATH="$HOME/.local/bin:$PATH"'
export PATH="$HOME/.local/bin:$PATH"
hash -r

# Step 5: Go
purge '^(golang-go|golang-src|golang-doc|golang-[0-9.]+-(go|src|doc))$'
sudo rm -rf /usr/local/go
wget -q -O /tmp/go.tar.gz "https://go.dev/dl/go${GO_VERSION}.linux-amd64.tar.gz"
sudo tar -C /usr/local -xzf /tmp/go.tar.gz
rm -f /tmp/go.tar.gz
env_add 'export PATH=$PATH:/usr/local/go/bin'
export PATH=$PATH:/usr/local/go/bin
sudo ln -sf /usr/local/go/bin/go /usr/local/bin/go
sudo ln -sf /usr/local/go/bin/gofmt /usr/local/bin/gofmt

# Step 6: CMake
purge '^(cmake|cmake-data|cmake-doc|cmake-curses-gui|cmake-qt-gui)$'
sudo rm -rf /usr/local/bin/{cmake,ctest,cpack,ccmake,cmake-gui} /usr/local/share/cmake-* /usr/local/doc/cmake-*
wget -q -O /tmp/cmake.sh "https://github.com/Kitware/CMake/releases/download/v${CMAKE_VERSION}/cmake-${CMAKE_VERSION}-linux-x86_64.sh"
sudo sh /tmp/cmake.sh --skip-license --prefix=/usr/local --exclude-subdir > /dev/null
rm -f /tmp/cmake.sh

# Step 7: ccache
purge '^ccache$'
sudo rm -f /usr/local/bin/ccache
_d="$(mktemp -d)"
wget -q -O "$_d/ccache.tar.xz" "https://github.com/ccache/ccache/releases/download/v${CCACHE_VERSION}/ccache-${CCACHE_VERSION}-linux-x86_64-glibc.tar.xz"
tar -xf "$_d/ccache.tar.xz" -C "$_d"
sudo install -m 0755 "$_d/ccache-${CCACHE_VERSION}-linux-x86_64-glibc/ccache" /usr/local/bin/ccache
rm -rf "$_d"

# Step 8: clang + libstdc++
# libllvmN 不在清理范围：mesa 依赖它。GCC 不清理：libstdc++6 依赖 gcc-N-base，purge 会连带拆掉大批系统库
purge '^((clang|lld|lldb|llvm|libclang|liblldb|python3-lldb)[a-z0-9.+-]*[0-9][a-z0-9.+-]*|clang|clang-format|clang-tidy|clangd|lld|lldb|llvm|libclang-dev|llvm-dev|iwyu)$'
sudo rm -f /usr/bin/{clang,clang++,clang-tidy,clang-format,clangd,lld,lldb,scan-build,clang-scan-deps,llvm-symbolizer,llvm-ar,llvm-ranlib,llvm-nm}
add_llvm_repo
apt_run install \
    "clang-${LLVM_VERSION}" "clang-tools-${LLVM_VERSION}" "clang-tidy-${LLVM_VERSION}" \
    "clang-format-${LLVM_VERSION}" "clangd-${LLVM_VERSION}" "lld-${LLVM_VERSION}" \
    "lldb-${LLVM_VERSION}" "llvm-${LLVM_VERSION}" "llvm-${LLVM_VERSION}-dev" "llvm-${LLVM_VERSION}-tools" \
    "libclang-${LLVM_VERSION}-dev" "libclang-rt-${LLVM_VERSION}-dev"
add_ppa ubuntu-toolchain-r/test C8EC952E2A0E1FBDC5090F6A2C277A0A352154E5
apt_run install "g++-${GCC_VERSION}" "libstdc++-${GCC_VERSION}-dev"
# clang-scan-deps: CMake modules 依赖扫描；llvm-symbolizer: sanitizer 报错符号化；llvm-ar/ranlib/nm: LTO
for _t in clang clang++ clang-tidy clang-format clangd lld lldb scan-build \
          clang-scan-deps llvm-symbolizer llvm-ar llvm-ranlib llvm-nm; do
    sudo ln -sf "/usr/bin/${_t}-${LLVM_VERSION}" "/usr/bin/${_t}"
done
# 钉死 libstdc++ 所用的 GCC：clang 默认取已装的最高版本，PPA 日后出 17 会悄悄换掉。
# 不装 libc++，标准库只用 libstdc++。实测 (strace) clang 只在软链解析后的真实目录找 .cfg，
# 且 clang++ 只认 clang++.cfg、不回退 clang.cfg，故两个都写在 /usr/lib/llvm-N/bin；
# 是否生效由验证段 check_cpp26 检查
sudo rm -f /usr/bin/clang.cfg
for _t in clang clang++; do
    echo "--gcc-install-dir=/usr/lib/gcc/x86_64-linux-gnu/${GCC_VERSION}" \
        | sudo tee "/usr/lib/llvm-${LLVM_VERSION}/bin/${_t}.cfg" > /dev/null
done
unset _t
env_add 'export CC=clang'
env_add 'export CXX=clang++'
export CC=clang
export CXX=clang++

# Step 9: Ninja
purge '^ninja-build$'
sudo rm -f /usr/local/bin/ninja
_d="$(mktemp -d)"
wget -q -O "$_d/ninja.zip" "https://github.com/ninja-build/ninja/releases/download/v${NINJA_VERSION}/ninja-linux.zip"
unzip -q -o "$_d/ninja.zip" -d "$_d"
sudo install -m 0755 "$_d/ninja" /usr/local/bin/ninja
rm -rf "$_d"

# Step 10: Mold
# 3.0.0 是 C++ → Rust 重写后的首个版本，选 C++ 版最后一版 2.42.1 求稳
purge '^mold$'
sudo rm -rf /usr/local/bin/{mold,ld.mold} /usr/local/lib/mold /usr/local/libexec/mold /usr/local/share/doc/mold
wget -q -O /tmp/mold.tar.gz "https://github.com/rui314/mold/releases/download/v${MOLD_VERSION}/mold-${MOLD_VERSION}-x86_64-linux.tar.gz"
sudo tar -xf /tmp/mold.tar.gz -C /usr/local --strip-components=1
rm -f /tmp/mold.tar.gz

# Step 11: GDB
# 装在独立前缀 /opt/gdb 便于整体 purge。libstdc++ 的 pretty-printer 在 /usr/share/gdb/auto-load，
# 非系统前缀的 gdb 默认不扫，须经 --with-auto-load-dir 追加
purge '^(gdb|gdb-multiarch|gdbserver|gdb-minimal)$'
sudo rm -rf /opt/gdb /usr/local/bin/{gdb,gdbserver,gdb-add-index,gcore,gstack}
apt_run install libgmp-dev libmpfr-dev libncurses-dev libexpat1-dev zlib1g-dev libzstd-dev "python${PYTHON_TARGET}-dev"
_d="$(mktemp -d)"
wget -q -O "$_d/gdb.tar.xz" "https://mirrors.aliyun.com/gnu/gdb/gdb-${GDB_VERSION}.tar.xz" \
    || wget -q -O "$_d/gdb.tar.xz" "https://ftp.gnu.org/gnu/gdb/gdb-${GDB_VERSION}.tar.xz"
tar -xf "$_d/gdb.tar.xz" -C "$_d"
mkdir "$_d/build"
(
    cd "$_d/build"
    "../gdb-${GDB_VERSION}/configure" --prefix=/opt/gdb \
        --with-python="python${PYTHON_TARGET}" --with-system-zlib --with-zstd \
        --with-auto-load-dir='$debugdir:$datadir/auto-load:/usr/share/gdb/auto-load' \
        --with-auto-load-safe-path=/usr:/opt/gdb > /dev/null
    make -j"$(nproc)" > /dev/null
    sudo make install > /dev/null
)
rm -rf "$_d"
for _t in gdb gdbserver gdb-add-index gcore gstack; do
    if [ -x "/opt/gdb/bin/${_t}" ]; then sudo ln -sf "/opt/gdb/bin/${_t}" "/usr/local/bin/${_t}"; fi
done
unset _d _t
hash -r

# Step 12: vcpkg
# 2026.10.16 自带 cmake 下限 4.4.3 (scripts/vcpkg-tools.json)，PATH 上的 4.4.4 会被直接复用
VCPKG_DIR="$HOME/vcpkg"
rm -rf "$VCPKG_DIR"
git clone -q --depth 1 --branch "$VCPKG_TAG" https://github.com/microsoft/vcpkg.git "$VCPKG_DIR"
"$VCPKG_DIR/bootstrap-vcpkg.sh" -disableMetrics > /dev/null
env_add 'export VCPKG_ROOT="$HOME/vcpkg"'
env_add 'export PATH="$VCPKG_ROOT:$PATH"'
export VCPKG_ROOT="$VCPKG_DIR"
export PATH="$VCPKG_ROOT:$PATH"
sudo ln -sf "$VCPKG_DIR/vcpkg" /usr/local/bin/vcpkg

# 验证
VERIFY_FAILED=0
check_tool() {
    local name="$1" cmd="$2" ver_cmd="$3" ver
    if command -v "$cmd" &> /dev/null; then
        ver="$(eval "$ver_cmd" 2>/dev/null | head -n1 || true)"
        printf "  \033[32m✓\033[0m %-14s %s\n" "$name" "${ver:-(version unknown)}"
    else
        printf "  \033[31m✗\033[0m %-14s NOT FOUND\n" "$name"
        VERIFY_FAILED=1
    fi
}

check_tool "Node.js"      node         "node -v"
check_tool "npm"          npm          "npm -v"
check_tool "claude"       claude       "claude --version"
check_tool "opencode"     opencode     "opencode --version"
check_tool "Python3"      python3      "python3 --version"
check_tool "Python"       python       "python --version"
check_tool "sys python3"  /usr/bin/python3 "/usr/bin/python3 --version"
check_tool "Go"           go           "go version"
check_tool "CMake"        cmake        "cmake --version"
check_tool "ccache"       ccache       "ccache --version"
check_tool "clang"        clang        "clang --version"
check_tool "clang++"      clang++      "clang++ --version"
check_tool "clang-tidy"   clang-tidy   "clang-tidy --version"
check_tool "clang-format" clang-format "clang-format --version"
check_tool "clangd"       clangd       "clangd --version"
check_tool "lld"          lld          "lld --version"
check_tool "lldb"         lldb         "lldb --version"
check_tool "scan-deps"    clang-scan-deps "clang-scan-deps --version"
check_tool "symbolizer"   llvm-symbolizer "llvm-symbolizer --version"
check_tool "llvm-ar"      llvm-ar      "llvm-ar --version"
check_tool "llvm-ranlib"  llvm-ranlib  "llvm-ranlib --version"
check_tool "llvm-nm"      llvm-nm      "llvm-nm --version"
check_tool "ninja"        ninja        "ninja --version"
check_tool "mold"         mold         "mold --version"
check_tool "gdb"          gdb          "gdb --version"
check_tool "git"          git          "git --version"
check_tool "vcpkg"        vcpkg        "vcpkg version"

# C++26 冒烟：pack indexing 是 C++26 语言特性；-v 输出用于确认 .cfg 生效且选中 GCC_VERSION 的 libstdc++
check_cpp26() {
    local d ok=1
    d="$(mktemp -d)"
    cat > "$d/t.cpp" <<'SRC'
#include <version>
template <class... T> constexpr auto first(T... t) { return t...[0]; }
int main() { return first(0, 1); }
SRC
    if clang++ -std=c++2c -stdlib=libstdc++ -fuse-ld=mold -v "$d/t.cpp" -o "$d/t" > "$d/log" 2>&1 && "$d/t"; then
        grep -q "Configuration file: " "$d/log" || { echo "    clang.cfg 未生效" >&2; ok=0; }
        grep -q "Selected GCC installation: .*/${GCC_VERSION}\$" "$d/log" || { echo "    未选中 GCC ${GCC_VERSION}" >&2; ok=0; }
    else
        tail -n 15 "$d/log" | sed 's/^/    /' >&2
        ok=0
    fi
    rm -rf "$d"
    if [ "$ok" -eq 1 ]; then
        printf "  \033[32m✓\033[0m %-14s clang++ -std=c++2c + libstdc++ %s + mold\n" "C++26" "$GCC_VERSION"
    else
        printf "  \033[31m✗\033[0m %-14s 冒烟编译失败\n" "C++26"
        VERIFY_FAILED=1
    fi
}
check_cpp26

if [ "$VERIFY_FAILED" -eq 0 ]; then
    echo -e "\033[32m✅ 所有工具验证通过\033[0m"
else
    echo -e "\033[31m⚠️  存在安装失败的工具\033[0m"
fi
echo -e "\033[33m👉 请执行 source ~/.bashrc 使环境变量在当前终端生效 (或重开终端)\033[0m"
echo -e "\033[33m   脚本 / cron / docker exec 等非交互场景: source $ENV_FILE (或 BASH_ENV=$ENV_FILE)\033[0m"

exit "$VERIFY_FAILED"
